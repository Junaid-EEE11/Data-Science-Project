AND A.CUST_ID=C.CUST_ID
AND M.CHECK_PT_METER_ID IN (SELECT  EQUIP_ID FROM EBC.bc_customer_meter WHERE CUSTOMER_NUM IN('2953977'))
AND C.LOCATION_CODE='D8'
AND C.SPL_TYPE = 'CPC'	
AND A.ADDR_TYPE='B'

