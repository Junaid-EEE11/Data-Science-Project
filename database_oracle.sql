        SUM(NVL(A.CURRENT_LPS,0)) LPS,SUM(NVL(A.CURRENT_VAT,0)) VAT
        --Round(NVL(a.ARR_ADV_ADJ_PRN,0)+NVL(A.ADJUSTED_PRN,0) +NVL(a.ARR_ADV_ADJ_VAT,0)+NVL(A.ADJUSTED_VAT,0)+NVL(a.ARR_ADV_ADJ_LPS,0)+NVL(A.CURRENT_LPS,0)+NVL(A.ADJUSTED_LPS,0)) Total_Arrear,
        --Round(NVL(Total_Bill,0)) Total_Bill 
FROM 
     BC_BILL_IMAGE A, 
     BC_CUSTOMERS b, 
     BC_CUSTOMER_ADDR c, 
     BC_LOCATION_MASTER d, 
     --BC_MONTHLY_LIKELY E, 
     BC_BUS_TYPE_CODE BT ,
     BC_CUSTOMER_OWNER_TYPE w,
     BC_MINISTRY_CODE Y,
     BC_CUSTOMER_TYPE_MST Z 
WHERE 
bill_cycle_code =:BC
AND A.CUST_ID = b.CUST_ID 
AND A.Location_Code=:Loc 
AND c.CUST_ID = b.CUST_ID 
--AND c.CUST_ID = E.CUST_ID 
and A.BUS_TYPE_CODE=BT.BUS_TYPE_CODE 
--AND E.EXP_DATE IS NULL 
AND A.LOCATION_CODE = d.LOCATION_CODE 
AND c.ADDR_TYPE = 'B' 
AND c.ADDR_EXP_DATE IS NULL 
AND SUBSTR(DECODE(LENGTH(A.CUST_STATUS),5,A.CUST_STATUS,'98715'),5,1)=W.CUSTOMER_OWNER_CODE
AND SUBSTR(DECODE(LENGTH(A.CUST_STATUS),5,A.CUST_STATUS,'98715'),1,2)=Y.MINISTRY_CODE
AND SUBSTR(DECODE(LENGTH(A.CUST_STATUS),5,A.CUST_STATUS,'98715'),3,2) = Z.CUSTOMER_TYPE_CODE
AND SUBSTR(DECODE(LENGTH(A.CUST_STATUS),5,A.CUST_STATUS,'98715'),5,1) in (1,2,3,4,5)  
--d NVL(a.ARR_ADV_ADJ_PRN,0)+NVL(A.ADJUSTED_PRN,0) +NVL(a.ARR_ADV_ADJ_VAT,0)+NVL(A.ADJUSTED_VAT,0)+NVL(a.ARR_ADV_ADJ_LPS,0)+NVL(A.CURRENT_LPS,0)+NVL(A.ADJUSTED_LPS,0)>10000
GROUP BY W.CODE_DESCR
ORDER BY 2 ASC
