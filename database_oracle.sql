SELECT W.CODE_DESCR Sector,COUNT(*),
--SUBSTR(A.AREA_CODE,1,3) Book, SUBSTR(A.AREA_CODE,4,2) BG,
--A.CUSTOMER_NUM||A.CONS_CHK_DIGIT Customer_No, 
--b.CUSTOMER_NAME CUSTOMER_NAME, 
--c.ADDR_DESCR1||', '||c.ADDR_DESCR2||'  '||c.ADDR_DESCR3 Address,  
         SUM(NVL(a.ENG_CHRG_SR,0)+NVL(a.ENG_CHRG_OFPK,0)+NVL(a.ENG_CHRG_PK,0)+NVL(a.PFC_CHARGE,0)+ 
        NVL(a.XF_LOSS_CHRG,0)+NVL(a.MINIMUM_CHRG,0)+nvl(a.XF_RENT,0)) UNIT_CHARGE,SUM(NVL(a.SERVICE_CHRG,0)) SEVICE,SUM(NVL(a.DEMAND_CHRG,0)) DEMAND, 
