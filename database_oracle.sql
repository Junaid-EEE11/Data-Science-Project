SELECT C.LOCATION_CODE LOCATION,C.AREA_CODE AREA,C.CUSTOMER_NUM CUSTOMER,C.CUSTOMER_NAME NAME,
A.ADDR_DESCR1||A.ADDR_DESCR2 ADDRESS,C.SPL_TYPE STYPE,M.EQUIP_ID MOTHER
FROM EBC.BC_CUSTOMERS C,EBC.BC_CUSTOMER_ADDR A,ebc.bc_customer_meter M
WHERE  A.CUST_ID=C.CUST_ID
AND M.CUST_ID=A.CUST_ID
AND C.CUSTOMER_NUM IN('2953977') ---=&CUST
AND C.LOCATION_CODE='F2'
AND C.SPL_TYPE IN ('CPR','CPV')
AND A.ADDR_TYPE='B'
--AND M.REPLACED_METER_ID IS NOT NULL
--AND M.REC_STATUS<>'U'
--ORDER BY M.EQUIP_ID
UNION 
SELECT C.LOCATION_CODE LOCATION,C.AREA_CODE AREA,C.CUSTOMER_NUM CUSTOMER,C.CUSTOMER_NAME NAME,
A.ADDR_DESCR1||A.ADDR_DESCR2 ADDRESS,C.SPL_TYPE STYPE,M.CHECK_PT_METER_ID MOTHER
